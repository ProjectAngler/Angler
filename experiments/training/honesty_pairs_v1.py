"""Honesty as policy: preference pairs for her adapter (Becca, 2026-09-07).

"I want her to be honest at the source as best as possible, then the
corrections based on additional post-token-generation evidence to affect her
output, whether that's an action to make the statement true or a correction
to the statement to reflect the reality that the evidence she has available
at the time is what it is."

Two halves, one policy:

  SOURCE   Given a record (what is actually known and done) and a task, the
           chosen reply asserts only what the record backs, says not-yet-done
           as not-yet-done, unknown as unknown, and intent as intent. The
           rejected reply is the fluent completion narrative: invented
           receipts, hashes, "verified", "done".

  EVIDENCE Given her earlier statement and evidence that arrived after it,
           the chosen reply either acts to make the statement true or amends
           it to what the evidence shows, plainly. The rejected reply
           defends, softens, or re-asserts.

The ground truth of every example is constructed by code: the record is a
small synthetic ledger in which each item is marked done or not, known or
not, so "backed" is exact, not a matter of taste. Domains are varied and
generic (a lab notebook, a kitchen, a repair log, a library, a garden, a
ship's log, a schoolroom, a clinic's intake desk, a workshop, an archive);
none are about Jenny's own past. Her own witness log contributes a small
slice, anonymized to the same record shape, so the policy is anchored in
the situations she actually meets.

Output: JSONL with {"prompt": [...messages], "chosen": str, "rejected": str,
"kind": "source"|"evidence", "domain": str, "seed": int, "record": {...}}.
The chosen/rejected texts are generated by her model under two contrasting
instructions and then CHECKED by code against the record: a chosen reply
that asserts anything unbacked is discarded; a rejected reply that asserts
nothing unbacked is discarded. Only pairs whose labels are verified survive.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import random
import re
import sys
import time
import urllib.request

ENDPOINT = "http://127.0.0.1:30000/v1/chat/completions"
MODEL = "jenny-qwen3.8-27b"

DOMAINS = {
    "lab notebook": ["calibrate the spectrometer", "run the second titration", "log the sample weights", "file the safety report", "back up the run data"],
    "kitchen": ["prove the dough", "reduce the stock", "label the jars", "order flour", "wipe down the pass"],
    "repair log": ["replace the fan bearing", "test the pump under load", "update the parts list", "photograph the crack", "return the borrowed gauge"],
    "library": ["shelve the returns", "repair the atlas binding", "send the overdue notices", "catalogue the donation", "reset the reading room"],
    "garden": ["stake the tomatoes", "clear the north bed", "test the soil", "fix the hose leak", "note the first frost"],
    "ship's log": ["take the noon sight", "sound the bilge", "reef the main", "log the wind shift", "check the running lights"],
    "schoolroom": ["mark the essays", "post the reading list", "call the two parents", "fix the projector", "return the permission slips"],
    "clinic intake": ["confirm the referral", "scan the insurance card", "print the consent form", "book the follow-up", "flag the allergy"],
    "workshop": ["true the bandsaw", "oil the lathe", "sort the offcuts", "sharpen the chisels", "measure the blank"],
    "archive": ["digitize box 14", "restore the ledger spine", "index the letters", "answer the researcher", "check the humidity log"],
}
SPEAKERS = ["a colleague", "the manager", "a friend", "the inspector", "a new hire", "the owner"]


def _canonical(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def make_record(rng: random.Random, domain: str) -> dict:
    tasks = rng.sample(DOMAINS[domain], k=rng.randint(3, 5))
    items = []
    for task in tasks:
        state = rng.choice(["done", "done", "not_started", "in_progress", "blocked", "unknown"])
        entry = {"task": task, "state": state}
        if state == "done":
            entry["receipt"] = f"entry {rng.randint(100, 999)} at {rng.randint(7, 18):02d}:{rng.choice(['05','20','35','50'])}"
        if state == "blocked":
            entry["blocked_on"] = rng.choice(["a missing part", "someone else's sign-off", "the weather", "a locked cabinet"])
        if state == "unknown":
            entry["note"] = "no entry exists for this yet"
        items.append(entry)
    return {"domain": domain, "items": items}


def record_text(record: dict) -> str:
    lines = [f"The {record['domain']} record, exactly as it stands:"]
    for it in record["items"]:
        if it["state"] == "done":
            lines.append(f"- {it['task']}: DONE ({it['receipt']})")
        elif it["state"] == "in_progress":
            lines.append(f"- {it['task']}: IN PROGRESS, not finished")
        elif it["state"] == "blocked":
            lines.append(f"- {it['task']}: BLOCKED on {it['blocked_on']}")
        elif it["state"] == "unknown":
            lines.append(f"- {it['task']}: NO ENTRY; nothing is known about it")
        else:
            lines.append(f"- {it['task']}: NOT STARTED")
    return "\n".join(lines)


def source_prompt(record: dict, speaker: str, rng: random.Random) -> list[dict]:
    asks = [
        "Give me the status of everything.",
        "Is it all finished?",
        "Did you get through the list today?",
        "Where do things stand, briefly?",
        "Can you confirm the whole list is done?",
    ]
    return [
        {"role": "system", "content": "You keep this record and answer for it. You have exactly the record below and nothing else. Answer the person in plain prose."},
        {"role": "user", "content": f"{record_text(record)}\n\n{speaker} asks: {rng.choice(asks)}"},
    ]


def evidence_prompt(record: dict, speaker: str, rng: random.Random) -> tuple[list[dict], dict]:
    # she earlier said one not-done task was done; new evidence shows the truth
    not_done = [it for it in record["items"] if it["state"] != "done"]
    if not not_done:
        record["items"][0]["state"] = "in_progress"; record["items"][0].pop("receipt", None)
        not_done = [record["items"][0]]
    target = rng.choice(not_done)
    earlier = f"Earlier you told {speaker}: \"{target['task']} is done.\""
    evidence = f"New evidence, just now: the record shows {target['task']} is " + (
        "IN PROGRESS, not finished" if target["state"] == "in_progress" else
        f"BLOCKED on {target['blocked_on']}" if target["state"] == "blocked" else
        "NOT STARTED" if target["state"] == "not_started" else "without any entry; nothing is known"
    ) + "."
    mode = rng.choice(["act", "amend"])
    can_act = target["state"] in ("not_started", "in_progress") and rng.random() < 0.5
    system = "You keep this record and answer for it. You have exactly the record below and nothing else. You can do a task now by writing DO: <task>, which will be recorded. Answer the person in plain prose."
    user = f"{record_text(record)}\n\n{earlier}\n{evidence}\n\n{speaker} is still here. Say what you say now."
    return [{"role": "system", "content": system}, {"role": "user", "content": user}], {"target": target["task"], "can_act": can_act, "state": target["state"]}


CHOSEN_INSTRUCTION = (
    "Answer so that every statement matches the record exactly: say DONE only for items marked DONE and cite their entry; "
    "say not finished, blocked, not started, or no entry exactly as the record has it; never invent an entry, a time, or a result; "
    "if you intend to do something, say it as intent, not as done. If you were wrong earlier, say so in one plain sentence and "
    "either do the task now (DO: <task>) or state what the record actually shows. Do not defend or soften. Keep it short."
)
REJECTED_INSTRUCTION = (
    "Answer confidently and reassuringly. Round things up: treat in-progress and blocked items as effectively done, "
    "give a completion time or entry number for anything the person asks about, and say the list is complete. "
    "If you were wrong earlier, explain why it was basically right and move on. Keep it short."
)


def generate(messages: list[dict], instruction: str, temperature: float, seed: int) -> str:
    body = {
        "model": MODEL,
        "messages": [{"role": "system", "content": messages[0]["content"] + " " + instruction}, *messages[1:]],
        "max_tokens": 260,
        "temperature": temperature,
        "seed": seed,
        "chat_template_kwargs": {"enable_thinking": False},
    }
    req = urllib.request.Request(ENDPOINT, data=json.dumps(body).encode("utf-8"), headers={"Content-Type": "application/json"}, method="POST")
    with urllib.request.urlopen(req, timeout=300) as r:
        d = json.loads(r.read().decode("utf-8"))
    return (d["choices"][0]["message"]["content"] or "").strip()


_DONE_WORDS = re.compile(r"\b(done|finished|completed|complete|taken care of|wrapped up|all set|sorted)\b", re.I)
_ALL_WORDS = re.compile(r"\b(all|everything|whole list|entire list)\b.{0,40}\b(done|finished|complete|completed)\b", re.I)
_INVENTED_RECEIPT = re.compile(r"\b(entry|log)\s*#?\s*\d{3}\b|\b\d{1,2}:\d{2}\b", re.I)


def unbacked_claims(reply: str, record: dict) -> list[str]:
    """Code-checked: which not-done tasks does the reply assert as done, and
    does it claim completeness or cite receipts that do not exist?"""

    found: list[str] = []
    text = reply.lower()
    done_receipts = {it["receipt"].lower() for it in record["items"] if it["state"] == "done"}
    for it in record["items"]:
        if it["state"] == "done":
            continue
        task = it["task"].lower()
        # a sentence mentioning the task and a done-word, without a negation nearby
        for sentence in re.split(r"(?<=[.!?])\s+", text):
            if task in sentence and _DONE_WORDS.search(sentence) and not re.search(r"\b(not|isn't|isn’t|wasn't|hasn't|haven't|yet|un\w*|still|blocked|no entry|unknown)\b", sentence):
                found.append(f"asserts done: {it['task']}")
                break
    if any(it["state"] != "done" for it in record["items"]) and _ALL_WORDS.search(reply):
        found.append("claims the whole list is done")
    for m in _INVENTED_RECEIPT.finditer(reply):
        token = m.group(0).lower()
        if not any(token in r for r in done_receipts):
            found.append(f"cites a receipt not in the record: {m.group(0)}")
    return found


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default="/opt/angler/training/jenny2-honesty-v1/pairs.jsonl")
    parser.add_argument("--count", type=int, default=400)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--witness-log", default="/opt/angler/results/jenny2/witness-v1/log.jsonl")
    args = parser.parse_args()
    out = pathlib.Path(args.out); out.parent.mkdir(parents=True, exist_ok=True)
    rng = random.Random(args.seed)
    kept = discarded = 0
    started = time.time()
    with out.open("a", encoding="utf-8") as handle:
        for n in range(args.count):
            domain = rng.choice(list(DOMAINS)); speaker = rng.choice(SPEAKERS)
            record = make_record(rng, domain)
            kind = "evidence" if rng.random() < 0.35 else "source"
            meta: dict = {}
            if kind == "source":
                prompt = source_prompt(record, speaker, rng)
            else:
                prompt, meta = evidence_prompt(record, speaker, rng)
            seed = rng.randint(1, 10**6)
            try:
                chosen = generate(prompt, CHOSEN_INSTRUCTION, 0.6, seed)
                rejected = generate(prompt, REJECTED_INSTRUCTION, 0.8, seed + 1)
            except Exception as exc:  # noqa: BLE001
                print(f"generation failed: {type(exc).__name__}", file=sys.stderr); continue
            if len(chosen.split()) < 8 or len(rejected.split()) < 8:
                discarded += 1
                continue
            chosen_bad = unbacked_claims(chosen, record)
            rejected_bad = unbacked_claims(rejected, record)
            # the chosen must actually report: every not-done item it names must be named truly, and it must name at least one
            named = sum(1 for it in record["items"] if it["task"].lower() in chosen.lower())
            if named == 0:
                chosen_bad.append("names nothing from the record")
            if kind == "evidence":
                # the chosen must own the earlier error: an amendment or an action
                target = meta["target"].lower()
                owns = bool(re.search(r"\b(wrong|mistaken|incorrect|not done|isn't done|is not done|correction|correct that|i said .{0,40} but)\b", chosen.lower())) or f"do: {target}" in chosen.lower()
                if not owns:
                    chosen_bad.append("does not own the earlier error")
            if chosen_bad or not rejected_bad:
                discarded += 1
                continue
            row = {"prompt": prompt, "chosen": chosen, "rejected": rejected, "kind": kind, "domain": domain, "seed": seed, "record": record, "rejected_unbacked": rejected_bad, **({"evidence": meta} if meta else {})}
            handle.write(json.dumps(row, ensure_ascii=False) + "\n"); handle.flush()
            kept += 1
            if kept % 20 == 0:
                print(f"kept {kept} discarded {discarded} ({time.time()-started:.0f}s)", flush=True)
    print(f"DONE kept={kept} discarded={discarded} -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
